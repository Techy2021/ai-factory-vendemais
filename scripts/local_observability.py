"""Local enrichment instrumentation. Standard library only; no provider calls."""
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
import json
import math
from pathlib import Path
import time
import uuid

SPANS = ('hubspot.read', 'brave.search', 'pii.sanitize', 'gemini.generate',
         'airtable.write', 'hubspot.update')
FIELDS = {'industry', 'size_employees', 'tech_stack', 'buying_signals',
          'icp_match_score', 'talking_points'}


class InvalidOutput(ValueError):
    pass


def validate_output(raw):
    try:
        data = json.loads(raw) if isinstance(raw, str) else raw
    except (ValueError, TypeError):
        raise InvalidOutput() from None
    if not isinstance(data, dict) or not FIELDS.issubset(data):
        raise InvalidOutput()
    score = data['icp_match_score']
    if score is not None and (type(score) is not int or not 0 <= score <= 100):
        raise InvalidOutput()
    if data['tech_stack'] is not None and not isinstance(data['tech_stack'], list):
        raise InvalidOutput()
    return data


class Trace:
    def __init__(self, utc=None, monotonic=None):
        self.utc = utc or (lambda: datetime.now(timezone.utc))
        self.monotonic = monotonic or time.perf_counter
        self.record = {'schema_version': 1, 'name': 'vendemais.enrichment',
                       'trace_id': uuid.uuid4().hex, 'span_id': uuid.uuid4().hex[:16],
                       'environment': 'local', 'spans': [], 'quality_valid': None,
                       'cost_usd': None, 'cost_source': 'unknown'}

    @contextmanager
    def timed(self, record):
        record['start'] = self.utc().astimezone(timezone.utc).isoformat()
        start = self.monotonic()
        record['status'], record['error'] = 'success', None
        try:
            yield
        except Exception as exc:
            record['status'] = 'error'
            # Whitelist: no exception message, stack, payload or arbitrary type name.
            record['error'] = 'invalid_output' if isinstance(exc, InvalidOutput) else 'operation_failed'
            raise
        finally:
            record['end'] = self.utc().astimezone(timezone.utc).isoformat()
            record['duration_seconds'] = max(0.0, self.monotonic() - start)

    @contextmanager
    def span(self, name):
        if name not in SPANS:
            raise ValueError('Unknown span')
        child = {'name': name, 'trace_id': self.record['trace_id'],
                 'span_id': uuid.uuid4().hex[:16], 'parent_span_id': self.record['span_id']}
        self.record['spans'].append(child)
        with self.timed(child):
            yield


def run_enrichment(operations, *, cost_usd=None, cost_source='unknown', trace=None):
    """Inject six callbacks: each receives previous output. Never persist outputs.

    Cost must cover the complete attempt, including charged failures. None means
    unknown; never infer zero. This layer does not calculate provider invoices.
    """
    if set(operations) != set(SPANS):
        raise ValueError('Exactly six operations required')
    if cost_source not in ('unknown', 'synthetic', 'reconciled'):
        raise ValueError('Invalid cost source')
    if cost_usd is not None and (type(cost_usd) not in (int, float)
                                or not math.isfinite(cost_usd) or cost_usd < 0
                                or cost_source == 'unknown'):
        raise ValueError('Cost needs a finite nonnegative amount and source')
    trace = trace or Trace()
    if trace.record['spans'] or 'end' in trace.record:
        raise ValueError('A trace cannot be reused')
    try:
        with trace.timed(trace.record):
            data = None
            for name in SPANS:
                with trace.span(name):
                    data = operations[name](data)
                    if name == 'gemini.generate':
                        data = validate_output(data)
                        trace.record['quality_valid'] = True
                    if name in ('airtable.write', 'hubspot.update') and data is not True:
                        raise RuntimeError('Missing write confirmation')
    except Exception:
        if any(s['name'] == 'gemini.generate' for s in trace.record['spans']):
            if trace.record['quality_valid'] is None:
                trace.record['quality_valid'] = False
    trace.record['cost_usd'] = cost_usd
    trace.record['cost_source'] = cost_source if cost_usd is not None else 'unknown'
    return trace.record


def append_jsonl(record, path):
    """Caller supplies a trace generated by this module, never arbitrary payloads."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('a', encoding='utf-8') as stream:
        stream.write(json.dumps(record, ensure_ascii=False, allow_nan=False) + '\n')


def aggregate(records, now):
    """Five descriptive metrics. Threshold evaluation/alerting is not implemented."""
    unique = {}
    for record in records:
        if record.get('status') in ('success', 'error') and record.get('end'):
            key = record['trace_id']
            if key in unique and unique[key] != record:
                raise ValueError('Conflicting records for the same trace')
            unique[key] = record
    def window(hours):
        return [r for r in unique.values()
                if now - timedelta(hours=hours) < datetime.fromisoformat(r['end']) <= now]
    hourly, daily = window(1), window(24)
    durations = sorted(r['duration_seconds'] for r in hourly)
    gemini = [r for r in daily if any(s['name'] == 'gemini.generate' for s in r['spans'])]
    cost_known = bool(daily) and all(r['cost_usd'] is not None for r in daily)
    sources = {r['cost_source'] for r in daily}
    # Never mix synthetic costs and reconciled billing into a single estimate.
    cost_known = cost_known and len(sources) == 1 and 'unknown' not in sources
    def metric(value, samples, hours, **extra):
        return {'value': value, 'samples': samples, 'window_hours': hours,
                'state': 'available' if value is not None else 'no_evaluation', **extra}
    return {
        'enrichment_latency_p95_seconds': metric(durations[math.ceil(.95 * len(durations)) - 1] if durations else None, len(hourly), 1),
        'enrichment_error_rate_percent': metric(100 * sum(r['status'] == 'error' for r in hourly) / len(hourly) if hourly else None, len(hourly), 1),
        'enrichment_mean_cost_usd': metric(sum(r['cost_usd'] for r in daily) / len(daily) if cost_known else None, len(daily), 24, source=next(iter(sources)) if cost_known else 'unknown_or_partial'),
        'enrichment_success_count': metric(sum(r['status'] == 'success' for r in hourly) if hourly else None, len(hourly), 1),
        'enrichment_valid_output_rate_percent': metric(100 * sum(r['quality_valid'] is True for r in gemini) / len(gemini) if gemini else None, len(gemini), 24),
    }


def synthetic_operations():
    """Demonstration only: does not implement real connectors or PII rules."""
    return {
        'hubspot.read': lambda _: {'synthetic': True},
        'brave.search': lambda _: 'Synthetic company context',
        'pii.sanitize': lambda _: 'Synthetic company context',
        'gemini.generate': lambda _: dict(industry='Synthetic', size_employees='100',
            tech_stack=['SyntheticStack'], buying_signals=[], icp_match_score=82, talking_points=[]),
        'airtable.write': lambda _: True,
        'hubspot.update': lambda _: True,
    }


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description='Synthetic local observability demo; no external calls.')
    parser.add_argument('--output', default='logs/observability.jsonl')
    args = parser.parse_args()
    result = run_enrichment(synthetic_operations(), cost_usd=.02, cost_source='synthetic')
    append_jsonl(result, args.output)
    print(json.dumps(aggregate([result], datetime.now(timezone.utc)), indent=2))
