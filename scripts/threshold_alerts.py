"""Local threshold evaluator and P2 lifecycle. No Slack/network calls."""
import argparse
from datetime import datetime, timedelta, timezone
import json
import math
from pathlib import Path
import re
import time
import uuid

from local_observability import aggregate, append_jsonl

ERROR = 'enrichment_error_rate_percent'
RULES = {
    'enrichment_latency_p95_seconds': (60, '>', 20),
    ERROR: (5, '>', 20),
    'enrichment_mean_cost_usd': (.03, '>', 20),
    'enrichment_success_count': (1, '<', 0),
    'enrichment_valid_output_rate_percent': (95, '<', 20),
}


def evaluate(metrics, *, pending=None, active=None, telemetry_complete=False,
             daily_cost_due=True, allow_synthetic=False):
    results = {}
    for name, (limit, operator, minimum) in RULES.items():
        metric = metrics.get(name, {})
        value, samples = metric.get('value'), metric.get('samples', 0)
        reason = None
        if name == 'enrichment_success_count':
            if pending is not True or active is not True:
                reason = 'demand_or_operation_not_confirmed'
            elif value is None and telemetry_complete:
                value = 0  # Confirmed complete empty window, not a missing collector.
        if name == 'enrichment_mean_cost_usd':
            if not daily_cost_due:
                reason = 'outside_daily_cost_evaluation'
            elif metric.get('source') != 'reconciled' and not (allow_synthetic and metric.get('source') == 'synthetic'):
                reason = 'cost_not_reconciled'
        if value is None or samples < minimum:
            reason = reason or 'missing_value_or_minimum_sample'
        elif type(value) not in (int, float) or not math.isfinite(value):
            reason = 'invalid_value'
        state = 'insufficient_data' if reason else ('alert' if (value > limit if operator == '>' else value < limit) else 'ok')
        results[name] = {'state': state, 'value': value, 'samples': samples,
                         'threshold': limit, 'operator': operator,
                         'window_hours': metric.get('window_hours'), 'reason': reason}
    return results


def advance_p2(evaluation, previous, now, related_trace_ids=()):
    """One accepted evaluation per five-minute bucket; gaps break streaks."""
    state = dict(previous or {})
    bucket = int(now.timestamp()) // 300
    last = state.get('bucket')
    if last is not None and bucket <= last:
        return state, []
    last_time = state.get('evaluated_at')
    if last_time is not None and now.timestamp() - last_time < 300:
        return state, []
    if last is None or bucket != last + 1:
        state['bad'], state['good'] = 0, 0
    condition = evaluation[ERROR]
    status = condition['state']
    state['bucket'] = bucket
    state['evaluated_at'] = now.timestamp()
    state['bad'] = state.get('bad', 0) + 1 if status == 'alert' else 0
    state['good'] = state.get('good', 0) + 1 if status == 'ok' else 0
    kind = None
    if not state.get('open') and state['bad'] >= 2:
        state.update(open=True, alert_id=uuid.uuid4().hex)
        kind = 'opened'
    elif state.get('open') and state['good'] >= 2:
        state['open'] = False
        kind = 'resolved'
    elif (state.get('open') and status == 'alert'
          and bucket - state.get('last_notification_bucket', bucket) >= 12):
        kind = 'reminder'
    if kind is None:
        return state, []
    state['last_notification_bucket'] = bucket
    # Only technical UUIDs generated by local instrumentation, never arbitrary text.
    related = sorted({value for value in related_trace_ids
                      if isinstance(value, str) and re.fullmatch(r'[0-9a-f]{32}', value)})[:5]
    event = {'event': kind, 'alert_id': state['alert_id'], 'at': now.isoformat(),
             'condition': 'error_rate > 5% / 60min; samples >= 20; two consecutive 5min evaluations',
             'priority': 'P2', 'audience': ['RevOps', 'integration_maintainer'],
             'intended_channel': 'Slack #vendemais-operacao',
             'delivery_channel': 'local_jsonl', 'environment': 'local',
             'value': condition['value'], 'samples': condition['samples'],
             'related_trace_ids': related,
             'recovery_condition': 'error_rate <= 5%; samples >= 20; two consecutive 5min evaluations'}
    return state, [event]


def run_once(telemetry_path, state_path, evaluation_path, alert_path, now, **options):
    records = [json.loads(line) for line in Path(telemetry_path).read_text(encoding='utf-8').splitlines() if line.strip()]
    if any(record.get('environment') != 'local' for record in records):
        raise ValueError('Only local telemetry is supported')
    metrics = aggregate(records, now)
    # Daily cost evaluation: 09:00 São Paulo (12:00 UTC), five-minute slot.
    evaluation = evaluate(metrics, daily_cost_due=now.hour == 12 and now.minute < 5, **options)
    path = Path(state_path)
    previous = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
    related = [record['trace_id'] for record in records
               if record.get('status') == 'error' and record.get('end')
               and now - timedelta(hours=1) < datetime.fromisoformat(record['end']) <= now]
    state, events = advance_p2(evaluation, previous, now, related)
    append_jsonl({'at': now.isoformat(), 'environment': 'local', 'metrics': evaluation}, evaluation_path)
    for event in events:
        append_jsonl(event, alert_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(state, allow_nan=False), encoding='utf-8')
    temp.replace(path)
    return evaluation, events


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--telemetry', default='logs/observability.jsonl')
    parser.add_argument('--directory', default='logs/thresholds')
    parser.add_argument('--watch', action='store_true', help='Evaluate every five minutes until interrupted.')
    parser.add_argument('--pending', action='store_true', default=None)
    parser.add_argument('--active', action='store_true', default=None)
    parser.add_argument('--telemetry-complete', action='store_true')
    parser.add_argument('--synthetic', action='store_true', help='Allow explicitly synthetic costs for demonstrations.')
    args = parser.parse_args()
    folder = Path(args.directory)
    try:
        while True:
            evaluation, events = run_once(args.telemetry, folder / 'state.json',
                folder / 'evaluations.jsonl', folder / 'alerts.jsonl', datetime.now(timezone.utc),
                pending=args.pending, active=args.active, telemetry_complete=args.telemetry_complete,
                allow_synthetic=args.synthetic)
            print(json.dumps({'metrics': evaluation, 'alerts': events}, allow_nan=False))
            if not args.watch:
                return 0
            time.sleep(300)
    except KeyboardInterrupt:
        return 0
    except (OSError, ValueError, KeyError, TypeError):
        print('Evaluation failed: check local telemetry/state. No fabricated recovery.')
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
